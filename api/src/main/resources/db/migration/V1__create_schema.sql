-- Portable SQL: runs unchanged on PostgreSQL (Docker) and H2 (local development and tests).

CREATE TABLE company (
    ticker           VARCHAR(12)              PRIMARY KEY,
    cik              CHAR(10)                 NOT NULL,
    name             VARCHAR(200)             NOT NULL,
    sector           VARCHAR(40)              NOT NULL,
    last_ingested_at TIMESTAMP WITH TIME ZONE
);

-- One row per company, metric, and fiscal year, with the filing it came from.
-- The yoy_* columns hold the change versus the prior year as measured within a single filing
-- that reports both years (null when no filing does), plus that filing's details.
CREATE TABLE annual_fact (
    ticker        VARCHAR(12)    NOT NULL REFERENCES company (ticker),
    metric        VARCHAR(40)    NOT NULL,
    period_end    DATE           NOT NULL,
    amount        NUMERIC(20, 2) NOT NULL,
    concept       VARCHAR(160)   NOT NULL,
    form          VARCHAR(12)    NOT NULL,
    filed         DATE           NOT NULL,
    accession     VARCHAR(25)    NOT NULL,
    yoy_change    NUMERIC(14, 6),
    yoy_concept   VARCHAR(160),
    yoy_form      VARCHAR(12),
    yoy_filed     DATE,
    yoy_accession VARCHAR(25),
    PRIMARY KEY (ticker, metric, period_end)
);

-- Audit trail for every load, so a failed or partial run is visible and explainable.
CREATE TABLE ingestion_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triggered_by VARCHAR(20)             NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    message     VARCHAR(1000)
);

CREATE TABLE ingestion_result (
    run_id       BIGINT       NOT NULL REFERENCES ingestion_run (id),
    ticker       VARCHAR(12)  NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    facts_loaded INT          NOT NULL,
    error        VARCHAR(1000),
    PRIMARY KEY (run_id, ticker)
);
